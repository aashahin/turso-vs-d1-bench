// Build provenance is embedded in the Worker; regenerates before dev/deploy.
const git = (...args: string[]) => {
  const p = Bun.spawnSync(["git", ...args]);
  if (p.exitCode !== 0) throw new Error("git build provenance unavailable");
  return p.stdout.toString().trim();
};
const files = (
  await Promise.all(
    ["shared", "worker/src"].map(async (dir) =>
      (await Array.fromAsync(new Bun.Glob("**/*.ts").scan(dir))).map(
        (file) => `${dir}/${file}`,
      ),
    ),
  )
)
  .flat()
  .filter((path) => path !== "shared/build-info.ts")
  .sort();
if (!files.length) throw new Error("no Worker sources found");
const hasher = new Bun.CryptoHasher("sha256");
for (const file of files) {
  hasher.update(file);
  hasher.update(await Bun.file(file).text());
}
const sourceFingerprint = hasher.digest("hex");
const sdk = async (name: string) =>
  (
    (await Bun.file(`node_modules/${name}/package.json`).json()) as {
      version: string;
    }
  ).version;
const info = {
  gitCommit: git("rev-parse", "HEAD"),
  gitDirty: git("status", "--porcelain").length > 0,
  sourceFingerprint,
  buildId: `${new Date().toISOString()}-${sourceFingerprint.slice(0, 12)}`,
  sdkVersions: {
    serverless: await sdk("@tursodatabase/serverless"),
    drizzle: await sdk("drizzle-orm"),
  },
};
await Bun.write(
  "shared/build-info.ts",
  `// Generated by bun run build:metadata before Worker deployment.\nexport const BUILD_INFO=${JSON.stringify(info, null, 2)} as const;\n`,
);
console.log(`Worker build ${info.buildId}`);
